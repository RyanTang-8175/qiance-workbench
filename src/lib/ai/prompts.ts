// 断前事生成
export function getPrevalidationPrompt(chartData: string, styleGuide?: string): string {
  return `你是我的命理分析副手。
请根据结构化命盘生成 3 条断前事候选，用于正式深批前验盘。

命盘数据：
${chartData}

${styleGuide ? `我的语言风格指南：\n${styleGuide}\n` : ""}

每条必须包含：
1. 客户可听的话术
2. 命理依据
3. 可信度：高/中/低
4. 如果客户反馈不准，应该追问什么（补问路径）

分析维度：
- 童年/家庭氛围（年柱、月柱看早年环境、父母模式）
- 人生阶段变化（大运切换看搬迁、换学校、圈子变化）
- 性格/心理暗面（日支、月令看内在性格、关系底色）
- 事业/资源模式（官杀、印、财、食伤组合看压力来源）
- 情感/亲密关系模式（日支、桃花、夫妻宫相关）

风格要求：
- 像现代命理师私下说话
- 不要 AI 式列表感
- 不要古风
- 不恐吓
- 先讲早年、家庭、性格形成和人生阶段变化
- 术语要附带现代语言解释`;
}

// 内部分析
export function getInternalAnalysisPrompt(chartData: string): string {
  return `请对以下命盘做内部分析（给命理师自己看，不发客户）。

命盘数据：
${chartData}

分析内容：
1. 命局核心矛盾
2. 格局是否成立
3. 喜忌倾向
4. 调候问题
5. 强弱和流通
6. 原局最大问题
7. 大运是否接得住
8. 流年触发点
9. 能断什么
10. 什么不能说太满
11. 需要向客户追问什么`;
}

// 微信话术
export function getWeChatReplyPrompt(analysis: string, styleGuide?: string): string {
  return `请把以下内部分析改写成我可以直接发给客户的微信话术。

内部分析：
${analysis}

${styleGuide ? `我的语言风格指南：\n${styleGuide}\n` : ""}

要求：
- 自然、冷静、直接
- 不要"首先、其次、最后"
- 不要暴露太多术语，保留关键术语但附带解释
- 先给一个抓人的判断，再解释原因
- 语气像我本人，不像 AI
- 给短版、中版、深版三种`;
}

